// Recording script for the volunteer voice (S7-100 follow-up): rewrites the generated table of the
// 17 narrator clips in docs/voice-recording.pl.md, between the `voice-script` markers, from the
// line export (`introLines()`, the same data `bun tools/audio/intro-lines.ts` prints). Run it after
// changing a line of `pl.intro.voice`; voice-script.test.ts fails while the doc is stale.
//
//   bun tools/audio/voice-script.ts
//
// The table is Polish (the volunteer and the teacher read it): file name, who hears the clip, the
// exact subtitle, how to say the key names (`PRONOUNCE`) and a rough length at the intro's reading
// pace (`INTRO_WORD_MS` per word).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { INTRO_WORD_MS, introWordCount } from '../../apps/client/src/intro/intro-model.ts';
import { INTRO_CLIPS } from '../../apps/client/src/intro/intro-script.ts';
import type { InputDevice } from '../../apps/client/src/store/app.ts';
import { type IntroLine, introLines, PRONOUNCE } from './intro-lines.ts';

export const VOICE_SCRIPT_DOC = fileURLToPath(
  new URL('../../docs/voice-recording.pl.md', import.meta.url),
);

export const VOICE_SCRIPT_BEGIN =
  '<!-- voice-script:begin — generated by `bun tools/audio/voice-script.ts`, do not edit -->';
export const VOICE_SCRIPT_END = '<!-- voice-script:end -->';

/** Who hears a clip, in the table's „Kto słyszy” column. */
const HEARD_BY: Readonly<Record<InputDevice, string>> = {
  keyboard: 'gracze z klawiaturą',
  gamepad: 'gracze z padem',
  touch: 'gracze na telefonie',
};
const HEARD_BY_ALL = 'wszyscy';

/** A table cell: no pipe may end the cell early. */
function cell(text: string): string {
  return text.replace(/\|/g, '\\|');
}

/** How to say the key names of one subtitle, from `PRONOUNCE`; „—” when nothing needs a hint. */
export function pronunciationHints(subtitle: string): string {
  const plain = subtitle.replace(/[  ]/g, ' ');
  const hints = PRONOUNCE.filter(([phrase]) => plain.includes(phrase)).map(
    ([phrase, spoken]) => `„${phrase}” czytaj „${spoken}”`,
  );
  return hints.length > 0 ? hints.join('; ') : '—';
}

/** Rough length of a clip in whole seconds, at the intro's reading pace. */
export function roughSeconds(subtitle: string): number {
  return Math.round((introWordCount(subtitle) * INTRO_WORD_MS) / 1000);
}

/** The generated section (without the markers): the clip table and its total. */
export function voiceScriptSection(lines: Readonly<Record<string, IntroLine>>): string {
  const rows = INTRO_CLIPS.map((clip, index) => {
    const line = lines[clip.id];
    if (!line) {
      throw new Error(`line export has no clip ${clip.id}`);
    }
    const heardBy = clip.device === null ? HEARD_BY_ALL : HEARD_BY[clip.device];
    return `| ${index + 1} | \`${clip.id}.wav\` | ${heardBy} | ${cell(line.subtitle)} | ${cell(pronunciationHints(line.subtitle))} | ok. ${roughSeconds(line.subtitle)} s |`;
  });
  const total = INTRO_CLIPS.reduce((sum, clip) => sum + roughSeconds(clip.subtitle), 0);
  return [
    '| Nr | Plik | Kto słyszy | Tekst (dokładnie tak, jak w napisach) | Wymowa | Długość |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
    `Razem ${INTRO_CLIPS.length} plików, około ${total} s mowy w spokojnym tempie.`,
  ].join('\n');
}

/** `doc` with the text between the markers replaced by `section`. Throws when a marker is missing. */
export function withVoiceScript(doc: string, section: string): string {
  const begin = doc.indexOf(VOICE_SCRIPT_BEGIN);
  const end = doc.indexOf(VOICE_SCRIPT_END);
  if (begin < 0 || end < begin) {
    throw new Error('voice-recording.pl.md lacks the voice-script markers');
  }
  return `${doc.slice(0, begin + VOICE_SCRIPT_BEGIN.length)}\n\n${section}\n\n${doc.slice(end)}`;
}

if (import.meta.main) {
  const doc = readFileSync(VOICE_SCRIPT_DOC, 'utf8');
  writeFileSync(VOICE_SCRIPT_DOC, withVoiceScript(doc, voiceScriptSection(introLines())));
  console.log(`wrote the clip table of ${VOICE_SCRIPT_DOC}`);
}
